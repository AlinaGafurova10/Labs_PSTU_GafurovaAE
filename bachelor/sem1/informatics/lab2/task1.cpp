#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std;

int main() {
    setlocale(LC_ALL, ".65001");
    
    // Инициализация переменных
    const double epsilon = 1e-4;  // Требуемая точность
    double sum = 0.0;              // Сумма ряда
    double a1 = 0.5;               // Первое слагаемое: b_1 = 1/2
    double a2 = 1.0/3.0;           // Второе слагаемое: c_1 = 1/3
    double an;                     // Общий член ряда
    int n = 1;                     // Номер члена ряда
    
    cout << "\nЧлены прогрессии:" << endl;
    cout << "------------------------------------------------------------" << endl;
    cout << "  n  |  a1=1/2^n  |  a2=1/3^n  |    an      |    Sum" << endl;
    cout << "------------------------------------------------------------" << endl;
    
    // Цикл суммирования с использованием рекуррентных формул
    do {
        an = a1 + a2;           // Вычисляем общий член ряда
        sum += an;              // Добавляем к сумме
        
        // Вывод промежуточных результатов
        cout << setw(3) << n << " | " 
             << fixed << setprecision(6) << setw(10) << a1 << " | "
             << setw(10) << a2 << " | "
             << setw(10) << an << " | "
             << setw(10) << sum << endl;
        
        // Рекуррентный переход к следующим членам
        a1 *= 0.5;              // a1_n+1 = a1_n * 1/2
        a2 *= (1.0/3.0);        // a2_n+1 = a2_n * 1/3
        n++;                    // Следующий номер
        
    } while (an >= epsilon);    // Продолжаем, пока an >= ε
    
    cout << "------------------------------------------------------------" << endl;
    
    // Вывод результатов
    cout << "\n========================================" << endl;
    cout << "РЕЗУЛЬТАТЫ:" << endl;
    cout << "========================================" << endl;
    cout << "Найденная сумма ряда: S = " << fixed << setprecision(6) << sum << endl;
    cout << "Количество членов ряда: n = " << n-1 << endl;
    cout << "Теоретическая сумма: S = 1.5" << endl;
    cout << "Абсолютная погрешность: " << abs(1.5 - sum) << endl;
    
    return 0;
}