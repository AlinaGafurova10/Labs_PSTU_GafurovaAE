#include <iostream>
#include <clocale>

using namespace std;

int main()
{
    setlocale(LC_ALL, ".65001");

    //Задача 1 
    cout << "Задача 1" << endl;
    int a = 10;
    int b = 20;
    int& r = a; // p и а ссылаются на одну ячейку, при изменении r меняется и а
    cout << r << endl;
    r = b; // r и а стали равны b
    r++;
    cout << a << " " << b << endl;

    //Задача 2 
    cout << "Задача 2" << endl;
    a = 12;
    int* ptr = &a; // ptr лежит адрес а
    cout << ptr << endl;
    int copy = *ptr; // в copy лежит значение а
    (*ptr)++; // изменяется значение а через ссылку ptr
    cout << a << " " << copy << endl;

    //Задача 3 
    cout << "Задача 3" << endl;
    a = 4;
    b = 9;
    int* p = &a; // здесь лежит адрес а
    cout << p << endl;
    int* q = p; // здесь лежит адрес а
    cout << q << endl;
    int& m = *p; // лежит значение а 
    cout << m << endl;
    p = &b; //переприсваиваем р адрес b
    *q += *p; // a = a + b = 4 + 9 = 13
    *p = m - 3; // b = a(13) - 3 = 10
    q = p; // q = ссылка на b 
    *q += m; // b = b + a = 10 + 13 = 23
    cout << a << " " << b << " " << m << endl;

    //Задача 4
    cout << "Задача 4" << endl;
    a = 5;
    b = 8;
    int& t = a; //t и а ссылаются на одну ячейку, при изменении t меняется и а
    int& s = a; // s и а ссылаются на одну ячейку, при изменении s меняется и а
    int cop = a; // лежит изначальное значение а = 5
    t = b; // a = b = 8
    s += 2;// a = a + 2 = 8 + 2 = 10
    b = cop; // b = 5
    cout << a << " " << b << " " << t << " " << s << " " << cop << endl;

    //Задача 5 
    cout << "Задача 5" << endl;
    a = 2;
    b = 5;
    int c = 8;
    int* g = &a; // лежит ссылка на а
    int& d = a; // d и а ссылаются на одну ячейку, при изменении d меняется и а
    int co = *g; // лежит значение а = 2
    *g = b; // a = b = 5
    g = &c; // в g переприсваивается ссыллка на c
    d = *g; // a = c = 8
    *g = b + co; // c = 5 + 2 = 7
    g = &b; // в g переприсваивается ссыллка на b
    *g = d - co; // b = a - co = 8 - 2 = 6
    d++; // a = a + 1 = 8 + 1 = 9
    cout << a << " " << b << " " << c << " " << co << endl;

    
    return 0;
}